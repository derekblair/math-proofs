"""Reproduce finite witness/census checks and generate the committed TikZ strip.

Run with --write-strip to regenerate strip.inc; otherwise only print the report.
This script is a supplementary reproducibility check. The Lean proof is in
Mathproofs/SidonSat184.lean and does not trust this script or its output.
"""
import argparse
import json
from collections import Counter
from itertools import combinations_with_replacement
from pathlib import Path

ASTAR = {16, 62, 66, 74, 88, 104, 117, 122, 123}
INTERVAL = set(range(1, 185))
CENSUS = [
    ({52,65,75,79,91,121,123,129,170},86),
    ({63,65,66,79,88,112,116,127,170},182),
    ({9,62,63,74,98,106,121,123,126},23),
    ({62,63,66,84,96,115,121,123,165},49),
    ({20,64,65,81,90,113,121,123,127},13),
    ({34,62,66,81,103,114,120,121,123},13),
    ({10,62,63,65,90,101,111,119,123},182),
    ({32,46,62,86,91,104,112,123,143},179),
    ({9,70,73,79,81,112,117,124,141},24),
]

def sums(a):
    return [x+y for x,y in combinations_with_replacement(sorted(a), 2)]

def sidon(a):
    s = sums(a)
    return len(s) == len(set(s))

def holes(a):
    return sorted(x for x in INTERVAL-a if sidon(a | {x}))

def report():
    assert len(ASTAR) == 9 and ASTAR <= INTERVAL and sidon(ASTAR)
    assert not holes(ASTAR)
    pair_sums = set(sums(ASTAR))
    multiplicities = {x: sum(x+a in pair_sums for a in ASTAR) + (2*x in pair_sums)
                      for x in INTERVAL-ASTAR}
    counts = dict(sorted(Counter(multiplicities.values()).items()))
    assert counts == {1:84, 2:57, 3:29, 4:5}
    extensions = []
    for label, (a, x) in enumerate(CENSUS, 13):
        assert sidon(a) and holes(a) == [x]
        extension = a | {x}
        assert len(extension) == 10 and sidon(extension) and not holes(extension)
        extensions.append({'row':label, 'added':x, 'saturated':True})
    return {'witness':sorted(ASTAR), 'size':9, 'pair_sums':sorted(pair_sums),
            'holes':[], 'blocking_multiplicity':counts, 'extensions':extensions}, multiplicities

def strip(multiplicities):
    lines = ['% Generated by verify_witness.py --write-strip; four rows of 46 positions.']
    for x in range(1,185):
        col, row = (x-1)%46, (x-1)//46
        color = 'mem' if x in ASTAR else f'blk{multiplicities[x]}'
        left, bottom = col*0.27, -row*0.65
        lines.append(rf'\filldraw[fill={color},draw=white,line width=0.2pt] '
                     rf'({left:.2f},{bottom:.2f}) rectangle ({left+0.26:.2f},{bottom+0.32:.2f});')
        if col in (0,45) or x%10 == 0:
            lines.append(rf'\node[font=\tiny,anchor=north] at ({left+0.13:.2f},{bottom-0.03:.2f}) {{{x}}};')
    return '\n'.join(lines)+'\n'

if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--write-strip', action='store_true')
    args = parser.parse_args()
    data, multiplicities = report()
    if args.write_strip:
        Path(__file__).with_name('strip.inc').write_text(strip(multiplicities))
    print(json.dumps(data, indent=2))
